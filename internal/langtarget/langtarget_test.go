func TestGoFiles_ImportsThePackageInsideTheModuleAndOverlaysMain(t *testing.T) {
	src := t.TempDir()
	if err := os.WriteFile(filepath.Join(src, "go.mod"), []byte("module example.com/ticketing\n\ngo 1.22\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	files, err := adapterFiles("go", languages["go"], "./internal/pricing:ChangeFee", src)
	if err != nil {
		t.Fatalf("adapterFiles returned unexpected error: %v", err)
	}
	main := string(files["main.go"])
	if !strings.Contains(main, `target "example.com/ticketing/internal/pricing"`) {
		t.Errorf("main.go does not import the entry's package:\n%s", main)
	}
	if !strings.Contains(main, "= target.ChangeFee") {
		t.Errorf("main.go does not bind the entry function:\n%s", main)
	}
	if strings.Contains(main, "{{") {
		t.Errorf("main.go still has an unfilled placeholder:\n%s", main)
	}

	var overlay struct{ Replace map[string]string }
	if err := json.Unmarshal(files["overlay.json"], &overlay); err != nil {
		t.Fatalf("overlay.json is not valid JSON: %v", err)
	}
	if got := overlay.Replace["/src/conjecture_adapter_main/main.go"]; got != "/adapter/main.go" {
		t.Errorf("overlay = %v, want main.go overlaid into the module", overlay.Replace)
	}
}

func TestGoFiles_RootPackageAndBadEntries(t *testing.T) {
	src := t.TempDir()
	if err := os.WriteFile(filepath.Join(src, "go.mod"), []byte("module example.com/app\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	files, err := adapterFiles("go", languages["go"], ".:Fee", src)
	if err != nil {
		t.Fatalf("adapterFiles for the module root returned unexpected error: %v", err)
	}
	if !strings.Contains(string(files["main.go"]), `target "example.com/app"`) {
		t.Errorf("a \".\" entry should import the module root itself:\n%s", files["main.go"])
	}

	for _, entry := range []string{"../other:Fee", "./pkg:fee", "./pkg:Fee()", "./pkg:"} {
		if _, err := adapterFiles("go", languages["go"], entry, src); err == nil {
			t.Errorf("adapterFiles accepted the entry %q, want an error", entry)
		}
	}
}

