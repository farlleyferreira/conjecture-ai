func TestLanguages_ListsTheSevenSupported(t *testing.T) {
	want := []string{"csharp", "go", "java", "javascript", "python", "ruby", "typescript"}
	got := Languages()
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Errorf("Languages() = %v, want %v", got, want)
	}
	for _, name := range got {
		if EntryForm(name) == "" {
			t.Errorf("EntryForm(%q) is empty, want a description of the entry", name)
		}
	}
}

func TestCanonical_ResolvesAliasesAndRejectsUnknown(t *testing.T) {
	cases := map[string]string{
		"py": "python", "Python": "python", "js": "javascript", "node": "javascript",
		"ts": "typescript", "golang": "go", "rb": "ruby", "cs": "csharp", "c#": "csharp", "dotnet": "csharp",
	}
	for in, want := range cases {
		got, ok := Canonical(in)
		if !ok || got != want {
			t.Errorf("Canonical(%q) = %q, %v, want %q, true", in, got, ok, want)
		}
	}
	if _, ok := Canonical("cobol"); ok {
		t.Error("Canonical(\"cobol\") = ok, want it rejected")
	}
}

func TestEveryLanguage_EmbedsItsAdapterFiles(t *testing.T) {
	for name, lang := range languages {
		for embedded := range lang.files {
			content, err := adapters.ReadFile("adapters/" + embedded)
			if err != nil {
				t.Errorf("%s: adapter file %s is not embedded: %v", name, embedded, err)
				continue
			}
			if !strings.Contains(string(content), "Generated by conjecture") {
				t.Errorf("%s: adapter file %s does not say it is generated", name, embedded)
			}
		}
	}
}

func TestPrepare_RejectsBadTargetsBeforeTouchingTheSandbox(t *testing.T) {
	src := t.TempDir()
	cases := []struct {
		name   string
		target Target
		want   string
	}{
		{"unknown language", Target{Lang: "cobol", Entry: "x:y", SrcDir: src}, "unsupported language"},
		{"missing entry", Target{Lang: "python", Entry: " ", SrcDir: src}, "--entry is required"},
		{"missing source directory", Target{Lang: "python", Entry: "m:f", SrcDir: filepath.Join(src, "nope")}, "does not exist"},
		{"go entry without a function", Target{Lang: "go", Entry: "./pkg", SrcDir: src}, "go entry must be"},
	}
	for _, c := range cases {
		// A sandbox whose binary does not exist: any attempt to run it
		// would surface as a different error than the one expected.
		_, err := Prepare(context.Background(), &sandbox.Sandbox{DockerBinary: filepath.Join(src, "no-such-runtime")}, c.target)
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: Prepare error = %v, want it to contain %q", c.name, err, c.want)
		}
	}
}

func TestPrepare_PythonNeedsNoBuildAndMountsSourceReadOnly(t *testing.T) {
	src := t.TempDir()
	prepared, err := Prepare(context.Background(), &sandbox.Sandbox{DockerBinary: filepath.Join(src, "no-such-runtime")},
		Target{Lang: "py", Entry: "pricing.fees:change_fee", SrcDir: src})
	if err != nil {
		t.Fatalf("Prepare returned unexpected error: %v", err)
	}

	if prepared.Image != "python:3-slim" {
		t.Errorf("Image = %q, want the stock python image", prepared.Image)
	}
	if got := strings.Join(prepared.Command, " "); got != "python3 /adapter/conjecture_adapter.py pricing.fees:change_fee" {
		t.Errorf("Command = %q, want the adapter followed by the entry", got)
	}
	if !contains(prepared.Env, "PYTHONPATH=/src") {
		t.Errorf("Env = %v, want PYTHONPATH=/src", prepared.Env)
	}

	var adapterDir string
	sawSrc := false
	for _, m := range prepared.Mounts {
		switch m.Container {
		case "/src":
			sawSrc = true
			if !m.ReadOnly {
				t.Error("the source mount is writable, want it read-only")
			}
		case "/adapter":
			adapterDir = m.Host
		}
	}
	if !sawSrc || adapterDir == "" {
		t.Fatalf("Mounts = %+v, want /src and /adapter", prepared.Mounts)
	}
	if _, err := os.Stat(filepath.Join(adapterDir, "conjecture_adapter.py")); err != nil {
		t.Errorf("the adapter was not written: %v", err)
	}

	prepared.Cleanup()
	if _, err := os.Stat(adapterDir); !os.IsNotExist(err) {
		t.Errorf("Cleanup left the adapter directory behind (stat error = %v)", err)
	}
}

